'use strict';
// Measure complete alpha-connected sprites; the source sheets do not use exact grid cells.
const fs=require('node:fs'),path=require('node:path'),zlib=require('node:zlib');
const root=path.join(__dirname,'..');
function decode(file){
  const png=fs.readFileSync(file),w=png.readUInt32BE(16),h=png.readUInt32BE(20);
  if(png[24]!==8||png[25]!==6||png[28]!==0)throw new Error('Esperado PNG RGBA 8 bits: '+file);
  const chunks=[];for(let p=8;p<png.length;){const length=png.readUInt32BE(p);if(png.toString('ascii',p+4,p+8)==='IDAT')chunks.push(png.subarray(p+8,p+8+length));p+=length+12;}
  const raw=zlib.inflateSync(Buffer.concat(chunks)),stride=w*4,pixels=Buffer.alloc(h*stride);
  for(let y=0;y<h;y++)for(let x=0;x<stride;x++){
    const filter=raw[y*(stride+1)],a=x>=4?pixels[y*stride+x-4]:0,b=y?pixels[(y-1)*stride+x]:0,c=y&&x>=4?pixels[(y-1)*stride+x-4]:0;
    let value=raw[y*(stride+1)+1+x];
    if(filter===1)value+=a;else if(filter===2)value+=b;else if(filter===3)value+=Math.floor((a+b)/2);
    else if(filter===4){const p=a+b-c,pa=Math.abs(p-a),pb=Math.abs(p-b),pc=Math.abs(p-c);value+=pa<=pb&&pa<=pc?a:pb<=pc?b:c;}
    else if(filter!==0)throw new Error('Filtro PNG inválido');
    pixels[y*stride+x]=value&255;
  }
  return {w,h,pixels};
}
function measure(file){
  const {w,h,pixels}=decode(file),seen=new Uint8Array(w*h),queue=new Int32Array(w*h),parts=[];
  for(let start=0;start<seen.length;start++){
    if(seen[start]||pixels[start*4+3]<=24)continue;
    let head=0,tail=1,minX=w,minY=h,maxX=0,maxY=0;queue[0]=start;seen[start]=1;
    while(head<tail){const p=queue[head++],x=p%w,y=Math.floor(p/w);minX=Math.min(minX,x);minY=Math.min(minY,y);maxX=Math.max(maxX,x);maxY=Math.max(maxY,y);
      for(const next of [x>0?p-1:-1,x<w-1?p+1:-1,y>0?p-w:-1,y<h-1?p+w:-1])if(next>=0&&!seen[next]&&pixels[next*4+3]>24){seen[next]=1;queue[tail++]=next;}
    }
    if(tail>3000)parts.push({x:minX,y:minY,w:maxX-minX+1,h:maxY-minY+1,pixelCount:tail});
  }
  if(parts.length!==16)throw new Error(path.basename(file)+': esperados 16 quadros, encontrados '+parts.length);
  parts.sort((a,b)=>(a.y+a.h/2)-(b.y+b.h/2));
  const referenceHeight=Math.max(...parts.map(p=>p.h)),result={};
  for(const [row,dir]of ['down','up','left','right'].entries()){
    result[dir]=parts.slice(row*4,row*4+4).sort((a,b)=>a.x-b.x).map(frame=>{
      let center=0,lines=0;
      for(let y=Math.floor(frame.y+frame.h*.2);y<frame.y+frame.h*.43;y++){
        let left=w,right=0;for(let x=frame.x;x<frame.x+frame.w;x++)if(pixels[(y*w+x)*4+3]>24){left=Math.min(left,x);right=Math.max(right,x);}
        if(left<=right){center+=(left+right)/2-frame.x;lines++;}
      }
      return {x:frame.x,y:frame.y,w:frame.w,h:frame.h,anchorX:Math.round((center/lines)*100)/100,referenceHeight};
    });
  }
  return result;
}
const output={};
for(const file of fs.readdirSync(path.join(root,'assets/npcs')).filter(f=>/^cliente-\d+\.png$/.test(f)).sort())output[path.basename(file,'.png')]=measure(path.join(root,'assets/npcs',file));
fs.writeFileSync(path.join(root,'js/client-frames.js'),'// Generated by node tools/build-client-frames.js.\n(function(root){root.PetClientFrames='+JSON.stringify(output,null,2)+';})(typeof globalThis!=="undefined"?globalThis:this);\n');
console.log('OK: '+Object.keys(output).length+' clientes, 16 quadros completos por cliente (frente, costas, esquerda e direita).');
